#!/usr/bin/env bash
# Build a bootable ZERO OS disk image (GPT + FAT32 EFI System Partition).
#
#   scripts/mkimage.sh <out.img> [kernel-cmdline] [kernel.elf]
#
# Uses only mtools + sgdisk on a plain file: no root, no mounting, and it can never
# touch a real disk (it refuses any output path that is a block device).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${1:?usage: mkimage.sh <out.img> [cmdline] [kernel.elf]}"
CMDLINE="${2:-}"
KERNEL="${3:-$ROOT/build/zero-kernel.elf}"
LIMINE_EFI="$ROOT/third_party/limine/BOOTX64.EFI"

die() { echo "mkimage: error: $*" >&2; exit 1; }

# Safety: only ever create/replace a plain file. Never a block/char device, directory or symlink.
[ -b "$OUT" ] && die "refusing to write to a block device ($OUT)"
if [ -e "$OUT" ] || [ -L "$OUT" ]; then
    [ -f "$OUT" ] && [ ! -L "$OUT" ] || die "refusing to overwrite $OUT: not a plain regular file"
fi
case "$CMDLINE" in
    *$'\n'*|*$'\r'*) die "kernel cmdline must be a single line" ;;
esac
for t in sgdisk mformat mmd mcopy truncate; do
    command -v "$t" >/dev/null || die "missing tool '$t' (run scripts/check-env.sh)"
done
[ -f "$KERNEL" ]     || die "kernel not found: $KERNEL (run 'make' first)"
[ -f "$LIMINE_EFI" ] || die "missing $LIMINE_EFI"

mkdir -p "$(dirname "$OUT")"
rm -f "$OUT"

IMG_MB=64
truncate -s ${IMG_MB}M "$OUT"
sgdisk -o -n 1:2048:0 -t 1:ef00 -c 1:"ZERO-ESP" "$OUT" >/dev/null

# Partition 1 starts at sector 2048 (1 MiB) and runs to the last usable sector.
PART_OFFSET=$((2048 * 512))
export MTOOLS_SKIP_CHECK=1
MT="$OUT@@$PART_OFFSET"
PART_SECTORS=$(( (IMG_MB * 1024 * 1024 - PART_OFFSET) / 512 - 34 ))

mformat -i "$MT" -F -T "$PART_SECTORS" -v ZEROESP ::
mmd -i "$MT" ::/EFI ::/EFI/BOOT ::/boot

CONF="$(mktemp)"
trap 'rm -f "$CONF"' EXIT
cat > "$CONF" <<EOF
# ZERO OS - Limine configuration (generated by scripts/mkimage.sh)
timeout: 0
serial: yes
quiet: yes

/ZERO OS
    protocol: limine
    path: boot():/boot/zero-kernel.elf
    cmdline: $CMDLINE
EOF

mcopy -i "$MT" "$LIMINE_EFI" ::/EFI/BOOT/BOOTX64.EFI
mcopy -i "$MT" "$CONF" ::/limine.conf
mcopy -i "$MT" "$KERNEL" ::/boot/zero-kernel.elf

echo "mkimage: wrote $OUT (cmdline: \"$CMDLINE\")"
